create or replace function private.production_can_insert_evidence(
  p_route_id bigint,
  p_stop_id bigint,
  p_pev_id bigint,
  p_evidence_type text,
  p_created_by uuid
)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(private.current_app_role() = 'production', false)
    and p_created_by = auth.uid()
    and p_evidence_type = 'weighing_scale'
    and exists (
      select 1
      from public.route_stops stop
      where stop.id = p_stop_id
        and stop.route_id = p_route_id
        and stop.pev_id = p_pev_id
        and private.production_can_access_stop(stop.id)
    )
$$;

create or replace function private.production_can_insert_weighing(
  p_route_id bigint,
  p_stop_id bigint,
  p_pev_id bigint,
  p_evidence_id bigint,
  p_created_by uuid
)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(private.current_app_role() = 'production', false)
    and p_created_by = auth.uid()
    and exists (
      select 1
      from public.route_stops stop
      where stop.id = p_stop_id
        and stop.route_id = p_route_id
        and stop.pev_id = p_pev_id
        and private.production_can_access_stop(stop.id)
    )
    and exists (
      select 1
      from public.route_evidences evidence
      where evidence.id = p_evidence_id
        and evidence.route_id = p_route_id
        and evidence.stop_id = p_stop_id
        and evidence.pev_id = p_pev_id
        and evidence.evidence_type = 'weighing_scale'
        and evidence.created_by = auth.uid()
    )
$$;

