using (
  exists (
    select 1
    from public.routes route
    where route.id = route_stops.route_id
      and (
        can_view_management()
        or (current_app_role() = 'driver' and route.driver_id = auth.uid())
      )
  )
  or (current_app_role() = 'commercial' and private.commercial_owns_pev(pev_id, auth.uid()))
  or private.production_can_access_stop(id)
