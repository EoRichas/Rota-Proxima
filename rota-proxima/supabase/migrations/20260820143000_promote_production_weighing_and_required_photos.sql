create or replace function private.production_can_access_route(p_route_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(private.current_app_role() = 'production', false)
    and exists (
      select 1
      from public.routes r
      where r.id = p_route_id
        and r.status = 'in_progress'
        and not exists (
          select 1
          from public.route_stops pending
          where pending.route_id = r.id
            and pending.status in ('pending','arrived')
        )
        and exists (
          select 1
          from public.route_stops collected
          where collected.route_id = r.id
            and collected.status = 'completed'
            and collected.service_type = 'collection'
            and not exists (
              select 1
              from public.route_weighings weighing
              where weighing.stop_id = collected.id
            )
        )
    )
$$;

create or replace function private.production_can_access_stop(p_stop_id bigint)
