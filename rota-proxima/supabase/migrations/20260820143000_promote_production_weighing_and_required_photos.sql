create or replace function private.require_driver_stop_photos()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_count integer;
begin
  if new.status in ('completed','failed')
     and old.status is distinct from new.status
     and private.current_app_role() = 'driver' then
    select count(distinct evidence.evidence_type)
      into v_count
    from public.route_evidences evidence
    where evidence.stop_id = new.id
      and evidence.evidence_type in ('stop_location','drum');

    if v_count <> 2 then
      raise exception 'As fotos do local e do tambor são obrigatórias antes de encerrar a parada'
        using errcode = 'check_violation';
    end if;
  end if;
  return new;
end
$$;

drop trigger if exists route_stops_require_driver_photos on public.route_stops;
create trigger route_stops_require_driver_photos
before update of status on public.route_stops
for each row execute function private.require_driver_stop_photos();

create or replace function private.finish_route_after_weighing()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_finished boolean := false;
begin
  update public.route_stops
     set collected_weight_kg = new.weight_kg
   where id = new.stop_id
     and route_id = new.route_id
     and pev_id = new.pev_id;

  update public.routes route
     set status = 'finished',
         finished_at = coalesce(route.finished_at, now())
   where route.id = new.route_id
     and route.status = 'in_progress'
     and not exists (
       select 1
       from public.route_stops pending
       where pending.route_id = route.id
         and pending.status in ('pending','arrived')
     )
     and not exists (
       select 1
       from public.route_stops collected
       where collected.route_id = route.id
         and collected.status = 'completed'
         and collected.service_type = 'collection'
         and not exists (
           select 1
           from public.route_weighings weighing
           where weighing.stop_id = collected.id
         )
     )
  returning true into v_finished;

  if coalesce(v_finished, false) then
    insert into public.audit_logs(
      actor_id,
      action,
      entity_type,
      entity_id,
      summary,
      metadata
    )
    values (
      new.created_by,
      'finish',
      'route',
      new.route_id::text,
      'Rota finalizada automaticamente após conclusão das paradas e pesagens',
      jsonb_build_object('automatic', true, 'source', 'production_weighing')
    );
  end if;

  return new;
end
$$;

drop trigger if exists route_weighings_finish_route on public.route_weighings;
create trigger route_weighings_finish_route
after insert on public.route_weighings
for each row execute function private.finish_route_after_weighing();

