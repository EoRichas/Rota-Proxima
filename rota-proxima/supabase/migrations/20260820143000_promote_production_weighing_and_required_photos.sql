create table if not exists public.route_evidences (
  id bigint generated by default as identity primary key,
  route_id bigint not null references public.routes(id) on delete cascade,
  stop_id bigint not null references public.route_stops(id) on delete cascade,
  pev_id bigint not null references public.pevs(id),
  evidence_type text not null,
  storage_path text not null,
  created_by uuid default auth.uid() references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  sharepoint_status text not null default 'pending',
  sharepoint_item_id text,
  sharepoint_url text,
  sharepoint_path text,
  sharepoint_sha256 text,
  sharepoint_synced_at timestamptz,
  sharepoint_started_at timestamptz,
  sharepoint_last_error text,
  sharepoint_attempts integer not null default 0,
  storage_deleted_at timestamptz,
  constraint route_evidences_evidence_type_check
    check (evidence_type = any (array['collection_material','delivery_drum_location','stop_location','drum','weighing_scale'])),
  constraint route_evidences_sharepoint_status_check
    check (sharepoint_status = any (array['pending','syncing','synced','error']))
);

create table if not exists public.route_weighings (
  id bigint generated by default as identity primary key,
  route_id bigint not null references public.routes(id) on delete cascade,
  stop_id bigint not null unique references public.route_stops(id) on delete cascade,
  pev_id bigint not null references public.pevs(id),
  weight_kg numeric not null check (weight_kg > 0),
  evidence_id bigint not null references public.route_evidences(id) on delete restrict,
  created_by uuid default auth.uid() references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

